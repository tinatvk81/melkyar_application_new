    "کولر گازی", "پکیج", "رادیاتور", "کولر آبی", "فن کویل", "چیلر",
    # کیفیت ساخت
    "بازسازی شده", "نوساز", "کلید نخورده", "سرعقب", "دو پارکینگ", "پارکینگ سندی",
    "کمد دیواری", "درب ضد سرقت", "درب ضدسرقت", "پنجره دوجداره", "دوجداره",
    "حمام مستر", "آشپزخانه اپن", "کابینت ام دی اف", "کابینت MDF", "کابینت گلس",
    "سنگ آنتیک", "سرامیک", "پارکت", "نورگیر عالی", "نور مستقیم",
